import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFile, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, "..");
const runner = resolve(root, "scripts/rnd-catalogue-runner.mjs");
const bundle = resolve(root, "scripts/.rnd-catalogue-runner.mjs");
const generatedDirectory = resolve(root, "src/app/core/game/rnd/generated");
const manifest = resolve(generatedDirectory, "rnd-catalogue.manifest.ts");
const checkOnly = process.argv.includes("--check");
const activateOnly = process.argv.includes("--activate");
const versionArgument = process.argv.indexOf("--version");
const requestedVersion = versionArgument >= 0 ? process.argv[versionArgument + 1] : undefined;
if (requestedVersion !== undefined && !/^v\d{3,}$/.test(requestedVersion)) throw new Error("Versione catalogo non valida. Usa, ad esempio, v002.");

const manifestSource = () => `/** Punto unico di attivazione del catalogo RDN. */\nexport const ACTIVE_RDN_CATALOGUE_ID = ${JSON.stringify(version)} as const;\n\nexport { RDN_CATALOGUE_METADATA, GENERATED_RDN_LEVELS, GENERATED_RDN_SOLUTION_AUDIT } from \"./catalogues/rnd-catalogue-${version}.generated\";\n`;
const currentManifest = await readFile(manifest, "utf8");
const activeMatch = currentManifest.match(/ACTIVE_RDN_CATALOGUE_ID = "(v\d+)"/);
const version = requestedVersion ?? activeMatch?.[1] ?? "v001";
const output = resolve(generatedDirectory, "catalogues", `rnd-catalogue-${version}.generated.ts`);

try {
  if (activateOnly) {
    await readFile(output, "utf8");
    await writeFile(manifest, manifestSource(), "utf8");
    console.info(`[RDN] Catalogo attivo: ${version}.`);
    process.exitCode = 0;
  } else {
  await build({ entryPoints: [runner], bundle: true, format: "esm", platform: "node", target: "node20", outfile: bundle, logLevel: "info" });
  const { catalogue } = await import(`${pathToFileURL(bundle).href}?generatedAt=${Date.now()}`);
  const payload = JSON.stringify(catalogue);
  const fingerprint = createHash("sha256").update(payload).digest("hex").slice(0, 16);
  const generated = `import type { LevelDefinition } from "../../puzzle.types";\n\n/** Generated by npm run rdn:catalogue. Do not edit by hand. */\nexport const RDN_CATALOGUE_METADATA = { generatedAt: ${JSON.stringify(new Date().toISOString())}, sourceFingerprint: ${JSON.stringify(fingerprint)}, validationPassed: true } as const;\n\nexport const GENERATED_RDN_LEVELS = ${JSON.stringify(catalogue.levels)} as unknown as readonly LevelDefinition[];\nexport const GENERATED_RDN_SOLUTION_AUDIT = ${JSON.stringify(catalogue.audit)} as unknown as readonly unknown[];\n`;

  if (checkOnly) {
    const current = await readFile(output, "utf8");
    if (!current.includes(`sourceFingerprint: ${JSON.stringify(fingerprint)}`)) throw new Error("Il catalogo RDN generato non è aggiornato. Esegui npm run rdn:catalogue.");
    console.info("[RDN] Catalogo generato aggiornato.");
  } else {
    await writeFile(output, generated, "utf8");
    console.info(`[RDN] Catalogo ${version} scritto: ${catalogue.levels.length} livelli, fingerprint ${fingerprint}.`);
  }
  }
} finally {
  await rm(bundle, { force: true });
}
